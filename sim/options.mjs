/**
 * Option audit (DESIGN-RULES A6, A9): what each turkey's knack and quirk is worth.
 *   node sim/options.mjs [--runs 12000] [--size 5] [--difficulty standard] [--out sim/OPTIONS.md]
 * For each turkey, the same games (same seeds, same rosters) are replayed with that
 * turkey's knack switched off, then its quirk switched off. The difference in win rate,
 * counted only over the games that turkey plays in, is the option's value in points.
 * Runs on every farm, split across worker processes.
 */
import { writeFileSync } from "node:fs";
import { fork } from "node:child_process";
import { fileURLToPath } from "node:url";
import { GG } from "../module/config.mjs";
import { makeRng } from "./rng.mjs";
import { playGame } from "./engine.mjs";
import { DEFAULTS } from "./params.mjs";

const arg = (name, dflt) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : dflt; };
const RUNS = Number(arg("runs", 12000)), SIZE = Number(arg("size", 5)), DIFF = arg("difficulty", "standard");
const OUT = arg("out", "sim/OPTIONS.md");
const IDS = GG.turkeys.map(t => t.id);

/** Win count over the games a turkey plays in, with an optional change to that turkey. */
function wins(farmId, focus, change) {
  const t = GG.turkeys.find(x => x.id === focus);
  const saved = { ...t };
  if (change) t[change] = "none";
  let win = 0, games = 0;
  for (let i = 0; i < RUNS; i++) {
    const rng = makeRng(5, farmId, DIFF, SIZE, i);
    const roster = rng.shuffle(IDS).slice(0, SIZE);
    if (!roster.includes(focus)) continue;
    games++;
    if (playGame({ farmId, difficulty: DIFF, roster, rng, params: DEFAULTS }).result === "win") win++;
  }
  Object.assign(t, saved);
  return { win, games };
}

if (process.argv.includes("--worker")) {
  const jobs = JSON.parse(arg("jobs", "[]"));
  const out = jobs.map(([farmId, id]) => {
    const base = wins(farmId, id), k = wins(farmId, id, "knack"), q = wins(farmId, id, "quirk");
    return { farmId, id, base, k, q };
  });
  process.send(out);
  process.exit(0);
}

const jobs = [];
for (const farmId of Object.keys(GG.farms)) for (const id of IDS) jobs.push([farmId, id]);
const W = 4;
const parts = Array.from({ length: W }, (_, w) => jobs.filter((_, i) => i % W === w));
const me = fileURLToPath(import.meta.url);
const results = (await Promise.all(parts.map(p => new Promise((res, rej) => {
  const c = fork(me, ["--worker", "--jobs", JSON.stringify(p), "--runs", String(RUNS), "--size", String(SIZE), "--difficulty", DIFF]);
  c.on("message", res); c.on("error", rej);
})))).flat();

const pts = (a, b) => 100 * (a.win / a.games - b.win / b.games);
const se = a => 100 * Math.sqrt(2 * (a.win / a.games) * (1 - a.win / a.games) / a.games);
const L = ["# Option audit", "",
  `Generated by \`node sim/options.mjs --runs ${RUNS} --size ${SIZE} --difficulty ${DIFF}\`. For each turkey, the games it plays in (about ${Math.round(RUNS * SIZE / 8)} per farm) are replayed with its knack switched off, then its quirk switched off. *Knack* is what the knack adds to the flock's win rate; *quirk* is what the quirk costs (negative means it hurts, as it should). Noise is about ±${se(results[0].base).toFixed(1)} points. DESIGN-RULES A9 flags an option worth less than 2 points either way.`, ""];
for (const farmId of Object.keys(GG.farms)) {
  L.push(`## ${GG.farms[farmId].name}`, "", "| Turkey | Knack | Worth | Quirk | Worth |", "|---|---|---|---|---|");
  for (const r of results.filter(x => x.farmId === farmId)) {
    const t = GG.turkeys.find(x => x.id === r.id);
    const kv = pts(r.base, r.k), qv = pts(r.base, r.q);
    const flag = v => Math.abs(v) < 2 ? ` ⚑` : "";
    L.push(`| ${t.name} | ${GG.knacks[t.knack].name} | ${kv >= 0 ? "+" : ""}${kv.toFixed(1)}${flag(kv)} | ${GG.quirks[t.quirk].name} | ${qv >= 0 ? "+" : ""}${qv.toFixed(1)}${flag(qv)} |`);
  }
  L.push("");
}
L.push("Average over the three farms:", "", "| Turkey | Knack | Worth | Quirk | Worth |", "|---|---|---|---|---|");
for (const id of IDS) {
  const rs = results.filter(x => x.id === id);
  const t = GG.turkeys.find(x => x.id === id);
  const kv = rs.reduce((s, r) => s + pts(r.base, r.k), 0) / rs.length, qv = rs.reduce((s, r) => s + pts(r.base, r.q), 0) / rs.length;
  L.push(`| ${t.name} | ${GG.knacks[t.knack].name} | ${kv >= 0 ? "+" : ""}${kv.toFixed(1)} | ${GG.quirks[t.quirk].name} | ${qv >= 0 ? "+" : ""}${qv.toFixed(1)} |`);
}
L.push("");
writeFileSync(OUT, L.join("\n"));
console.log(L.join("\n"));
