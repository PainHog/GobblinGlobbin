/**
 * Don't Get Gobble Gobbled — balance report.
 *   node sim/run.mjs [--runs 2000] [--seed 1] [--out sim/REPORT.md]
 * Plays every farm × difficulty × flock size (2–8) by the core rules with the
 * default flock policy, then the policy-sensitivity presets, and writes REPORT.md.
 * Same seed and runs → the same report.
 */
import { writeFileSync } from "node:fs";
import { GG } from "../module/config.mjs";
import { makeRng } from "./rng.mjs";
import { playGame } from "./engine.mjs";
import { DEFAULTS, PRESETS } from "./params.mjs";

const arg = (name, dflt) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : dflt; };
const RUNS = Number(arg("runs", 2000)), SEED = Number(arg("seed", 1)), OUT = arg("out", "sim/REPORT.md");
const SIZES = [2, 3, 4, 5, 6, 7, 8];
const DIFFS = Object.keys(GG.difficulty);
const FARMS = Object.keys(GG.farms);
const IDS = GG.turkeys.map(t => t.id);

/** Balance targets agreed for the core rules (docs/DESIGN.md, Decisions log). */
export const TARGETS = {
  easy:     { win: [85, 93], label: "about 9 in 10" },
  standard: { win: [74, 86], label: "about 4 in 5" },
  hard:     { win: [52, 68], label: "about 3 in 5" },
  rounds: [8, 15],
  rescueSuccess: [50, 80],
  savedWhenSpotted: [75, 95],
  feathersSpent: 0.5
};

/** Minutes per round at the table: about a minute per turkey plus two for the farmer (an estimate, not measured). */
const minutes = (rounds, n) => rounds * (n + 2);

function cell(farmId, difficulty, n, params, runs = RUNS, tag = "") {
  const a = { win: 0, rounds: 0, spottedGames: 0, spotted: 0, rescueTries: 0, rescueWins: 0, scramTries: 0, scramWins: 0,
    gob: { roll: 0, full: 0, letItOut: 0, rescue: 0, helper: 0 }, feathersSpent: 0, feathersStart: 0, pushes: 0, helps: 0,
    pranks: {}, prankClock: 0, decoy: 0, rolls: { n: 0, ok: 0, great: 0, gobble: 0 }, clutch: 0, roundsHist: {}, gobbled: {} };
  for (let i = 0; i < runs; i++) {
    const rng = makeRng(SEED, tag, farmId, difficulty, n, i);
    const roster = rng.shuffle(IDS).slice(0, n);
    const g = playGame({ farmId, difficulty, roster, rng, params });
    const s = g.stats;
    if (g.result === "win") a.win++; else a.gobbled[g.gobbled] = (a.gobbled[g.gobbled] ?? 0) + 1;
    a.rounds += g.rounds; a.roundsHist[g.rounds] = (a.roundsHist[g.rounds] ?? 0) + 1;
    a.spottedGames += s.spottedGames; a.spotted += s.spotted;
    a.rescueTries += s.rescueTries; a.rescueWins += s.rescueWins; a.scramTries += s.scramTries; a.scramWins += s.scramWins;
    for (const k in a.gob) a.gob[k] += s.gobbles[k];
    a.feathersSpent += s.feathersSpent; a.feathersStart += s.feathersStart; a.pushes += s.pushes; a.helps += s.helps;
    for (const k in s.pranks) a.pranks[k] = (a.pranks[k] ?? 0) + 1;
    a.prankClock += s.prankClock; a.decoy += s.decoyUsed; if (s.clutch) a.clutch++;
    for (const r of Object.values(s.rolls)) { a.rolls.n += r.n; a.rolls.ok += r.ok; a.rolls.great += r.great; a.rolls.gobble += r.gobble; }
  }
  a.runs = runs;
  return a;
}

const pct = (x, d = 0) => `${(100 * x).toFixed(d)}%`;
const f1 = x => x.toFixed(1);
const inBand = (v, [lo, hi]) => v >= lo && v <= hi;

const results = {};
for (const farm of FARMS) for (const d of DIFFS) for (const n of SIZES) results[`${farm}|${d}|${n}`] = cell(farm, d, n, DEFAULTS);

const L = [];
L.push("# Simulator report");
L.push("");
L.push(`Generated by \`node sim/run.mjs --runs ${RUNS} --seed ${SEED}\`: ${RUNS} games per farm, difficulty and flock size (${FARMS.length * DIFFS.length * SIZES.length * RUNS} games), played strictly by \`docs/CORE-RULES.md\` with the default flock policy (\`sim/policy.mjs\`). Same seed, same report.`);
L.push("");
L.push("**How to read it.** A *win* is reaching Too Late on the Dinner Clock with nobody caught; a *loss* is the farmer grabbing a turkey (it gets gobbled). The policy is a sensible way to play, not perfect play; §6 shows how much a timid or a bold flock changes the numbers.");
L.push("");

// ---- 1. headline
L.push("## 1. Win rate by difficulty and flock size");
L.push("");
L.push(`Targets: Easy ${TARGETS.easy.win.join("–")}%, Standard ${TARGETS.standard.win.join("–")}%, Hard ${TARGETS.hard.win.join("–")}%. A cell outside its band is marked **bold**.`);
L.push("");
for (const farm of FARMS) {
  L.push(`### ${GG.farms[farm].name}`);
  L.push("");
  L.push(`| Difficulty | ${SIZES.map(n => `${n} turkeys`).join(" | ")} |`);
  L.push(`|---|${SIZES.map(() => "---").join("|")}|`);
  for (const d of DIFFS) {
    const row = SIZES.map(n => {
      const a = results[`${farm}|${d}|${n}`]; const w = 100 * a.win / a.runs;
      const s = `${w.toFixed(0)}%`;
      return inBand(w, TARGETS[d].win) ? s : `**${s}**`;
    });
    L.push(`| ${GG.difficulty[d].name} | ${row.join(" | ")} |`);
  }
  L.push("");
}
L.push("Loss rate is 100% minus the win rate: every loss is one turkey gobbled, and the game can't end any other way (the farmer grabs a turkey, or the clock reaches Too Late).");
L.push("");

// ---- 2. length
L.push("## 2. Game length");
L.push("");
L.push(`Rounds per game (target ${TARGETS.rounds.join("–")}), and an estimated table time of about a minute per turkey plus two for the farmer per round, plus 15 minutes of setup.`);
L.push("");
L.push(`| Farm | Difficulty | ${SIZES.map(n => `${n}`).join(" | ")} |`);
L.push(`|---|---|${SIZES.map(() => "---").join("|")}|`);
for (const farm of FARMS) for (const d of DIFFS) {
  L.push(`| ${GG.farms[farm].name} | ${GG.difficulty[d].name} | ${SIZES.map(n => { const a = results[`${farm}|${d}|${n}`]; const r = a.rounds / a.runs; return `${f1(r)} (${Math.round(minutes(r, n) + 15)} min)`; }).join(" | ")} |`);
}
L.push("");

// ---- 3. rescue
L.push("## 3. Getting spotted, and getting saved");
L.push("");
L.push("Per game: how often at least one turkey is Spotted, how many Spotted moments there are, how often a friend tries Gobble for a Friend and how often it works, how often a Scram works, and the share of Spotted moments that end with the turkey saved.");
L.push("");
L.push("| Farm | Difficulty | Turkeys | Games with a Spotted turkey | Spotted moments / game | Rescues tried / game | Rescue works | Scram works | Saved when Spotted |");
L.push("|---|---|---|---|---|---|---|---|---|");
for (const farm of FARMS) for (const d of DIFFS) for (const n of [2, 4, 6, 8]) {
  const a = results[`${farm}|${d}|${n}`];
  const lost = a.runs - a.win;
  const saved = a.spotted ? 1 - lost / a.spotted : 1;
  L.push(`| ${GG.farms[farm].name} | ${GG.difficulty[d].name} | ${n} | ${pct(a.spottedGames / a.runs)} | ${f1(a.spotted / a.runs)} | ${(a.rescueTries / a.runs).toFixed(2)} | ${a.rescueTries ? pct(a.rescueWins / a.rescueTries) : "–"} | ${a.scramTries ? pct(a.scramWins / a.scramTries) : "–"} | ${pct(saved)} |`);
}
L.push("");

// ---- 4. the gobble and the resources
L.push("## 4. Gobbles, Feathers, pushes and help (Standard, all farms)");
L.push("");
L.push(`Feathers spent is the share of the flock's starting Feathers used (A7: at least ${pct(TARGETS.feathersSpent)}).`);
L.push("");
L.push("| Turkeys | Gobbles from the dice / game | Full-urge gobbles | Let It Out | Gobble for a Friend | Helpers' gobbles | Feathers spent | Pushes / game | Helps / game | Rolls: works | Great (any white 6) | A roll gobbles |");
L.push("|---|---|---|---|---|---|---|---|---|---|---|---|");
for (const n of SIZES) {
  const as = FARMS.map(f => results[`${f}|standard|${n}`]);
  const sum = k => as.reduce((s, a) => s + (typeof k === "function" ? k(a) : a[k]), 0);
  const runs = sum("runs");
  const r = { n: sum(a => a.rolls.n), ok: sum(a => a.rolls.ok), great: sum(a => a.rolls.great), gobble: sum(a => a.rolls.gobble) };
  L.push(`| ${n} | ${(sum(a => a.gob.roll) / runs).toFixed(2)} | ${(sum(a => a.gob.full) / runs).toFixed(2)} | ${(sum(a => a.gob.letItOut) / runs).toFixed(2)} | ${(sum(a => a.gob.rescue) / runs).toFixed(2)} | ${(sum(a => a.gob.helper) / runs).toFixed(2)} | ${pct(sum("feathersSpent") / Math.max(1, sum("feathersStart")))} | ${f1(sum("pushes") / runs)} | ${f1(sum("helps") / runs)} | ${pct(r.ok / r.n)} | ${pct(r.great / r.n)} | ${pct(r.gobble / r.n)} |`);
}
L.push("");

// ---- 5. pranks
L.push("## 5. Pranks (Standard, 4 turkeys)");
L.push("");
L.push("Share of games in which each prank gets pulled, and how far pranks moved the clock on average.");
L.push("");
for (const farm of FARMS) {
  const a = results[`${farm}|standard|4`];
  L.push(`**${GG.farms[farm].name}** (pranks moved the clock ${f1(a.prankClock / a.runs)} spaces a game; the decoy saved a turkey in ${pct(a.decoy / a.runs, 1)} of games): ` +
    GG.farms[farm].pranks.map(p => `${p.name} ${pct((a.pranks[p.id] ?? 0) / a.runs)}`).join(" · "));
  L.push("");
}

// ---- 6. policy sensitivity
L.push("## 6. How much the way you play matters (Standard, 4 turkeys)");
L.push("");
L.push("The same games with a *timid* flock (calms down early, rarely pranks), a *bold* one (pranks a lot, pushes often), and one that never pranks at all. If never pranking were best, pranks would be a trap; if it were hopeless, hiding would be.");
L.push("");
L.push("| Farm | Default | Timid | Bold | No pranks |");
L.push("|---|---|---|---|---|");
for (const farm of FARMS) {
  const w = p => { const a = cell(farm, "standard", 4, { ...DEFAULTS, ...PRESETS[p] }, RUNS, p); return pct(a.win / a.runs); };
  L.push(`| ${GG.farms[farm].name} | ${pct(results[`${farm}|standard|4`].win / RUNS)} | ${w("timid")} | ${w("bold")} | ${w("noPranks")} |`);
}
L.push("");
L.push("| Turkeys (Bramble Farm, Standard) | Default | No pranks |");
L.push("|---|---|---|");
for (const n of [2, 4, 6, 8]) {
  const a = cell("bramble", "standard", n, { ...DEFAULTS, ...PRESETS.noPranks }, RUNS, "np");
  L.push(`| ${n} | ${pct(results[`bramble|standard|${n}`].win / RUNS)} | ${pct(a.win / a.runs)} |`);
}
L.push("");

// ---- 7. who gets gobbled
L.push("## 7. Who gets gobbled (Standard, all farms and sizes)");
L.push("");
L.push("Share of losses in which each turkey was the one caught, against its share of seats. A turkey far above its seat share is a liability; far below, a safe pick.");
L.push("");
{
  const caught = {}, seats = {};
  let losses = 0;
  for (const farm of FARMS) for (const n of SIZES) {
    const a = results[`${farm}|standard|${n}`];
    for (const [id, v] of Object.entries(a.gobbled)) { caught[id] = (caught[id] ?? 0) + v; losses += v; }
  }
  L.push("| Turkey | Knack | Quirk | Share of the gobbled |");
  L.push("|---|---|---|---|");
  for (const t of GG.turkeys) L.push(`| ${t.name} | ${GG.knacks[t.knack].name} | ${GG.quirks[t.quirk].name} | ${pct((caught[t.id] ?? 0) / losses)} (seat share 12.5%) |`);
}
L.push("");
L.push("Option values (what each knack and quirk is worth in win points) are in `sim/OPTIONS.md` (`node sim/options.mjs`).");
L.push("");

writeFileSync(OUT, L.join("\n") + "\n");
console.log(`wrote ${OUT}`);
