/**
 * Printable sheets written from the game data (module/config.mjs):
 *   node book/tools/sheets.mjs
 *     → book/src/chapters/42-sheet-turkeys-1.html, 43-sheet-turkeys-2.html (turkey cards)
 *     → book/src/chapters/44-sheet-clock.html (the Dinner Clock and flock tracker)
 *     → book/src/chapters/45-sheet-tokens.html (tokens to cut out)
 * The knack and quirk text on the cards is the same text the rules use, so the cards
 * can't drift from Chapter 2. test/book-data.test.mjs checks the files are up to date.
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { GG } from "../../module/config.mjs";
import { clockStart } from "../../module/logic/rules.mjs";

const CH = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "chapters");
const BIRD = { hen: "hen", tom: "tom", jake: "jake (a young male)" };

function card(t) {
  const k = GG.knacks[t.knack], q = GG.quirks[t.quirk];
  const n = GG.turkeys.indexOf(t) + 1;
  return `    <div class="card" id="card-${t.id}">
      <h3>${t.name} <span class="card-num">${n}</span></h3>
      <p class="card-breed">${t.breed} ${BIRD[t.bird]}</p>
      <figure class="art card-draw" data-art="turkey-${t.id}"></figure>
      <p class="card-knack"><strong>Knack: ${k.name}.</strong> ${k.text}</p>
      <p class="card-quirk"><strong>Quirk: ${q.name}.</strong> ${q.text}</p>
      <div class="urge">Urge <span class="u">0</span><span class="u">1</span><span class="u">2</span><span class="u">3</span><span class="u">4</span><span class="u">5</span></div>
      <p class="card-foot">Start at urge 1. Red dice = your urge. Past 5: gobble, back to 0 (no Feather can stop it).</p>
    </div>`;
}

function turkeySheet(n, turkeys) {
  return `<!-- Generated by book/tools/sheets.mjs from module/config.mjs: edit those, not this file. -->
<section class="sheet" id="sheet-turkeys-${n}">
  <h2>Turkey Cards (${n} of 2)</h2>
  <div class="cards">
${turkeys.map(card).join("\n")}
  </div>
</section>
`;
}

function clockSheet() {
  const max = Math.max(...Object.values(GG.farms).flatMap(f => Object.keys(GG.difficulty).flatMap(d => [2, 3, 4, 5, 6, 7, 8].map(n => clockStart(d, n, f)))));
  const sp = [];
  for (let i = max; i >= 1; i--) {
    const pie = i % GG.clock.eventEvery === 0;
    sp.push(`    <div class="sp${pie ? " pie" : ""}">${i}${pie ? "<small>event</small>" : ""}</div>`);
  }
  sp.push(`    <div class="sp late">TOO LATE!<small>the flock wins</small></div>`);
  return `<!-- Generated by book/tools/sheets.mjs from module/config.mjs: edit those, not this file. -->
<section class="sheet" id="sheet-clock">
  <h2>The Dinner Clock</h2>
  <p class="sheet-intro">Put a coin on the starting space (Chapter 8). It moves down 1 at the end of every round, and further when a prank happens. On an EVENT space, or jumping past one, the Storyteller rolls a farm event.</p>
  <div class="clock-track">
${sp.join("\n")}
  </div>
  <div class="tracker-row">
    <div>
      <div class="field"><strong>Feathers</strong> (cross one off when it’s spent)</div>
      <div class="boxes"><span></span><span></span><span></span><span></span></div>
    </div>
    <div>
      <div class="field"><strong>Decoy ready</strong> (tick when it’s made; cross out when it’s used)</div>
      <div class="boxes"><span></span></div>
    </div>
    <div>
      <div class="field"><strong>Next farmer’s turn</strong></div>
      <p>Rake: doesn’t walk <span class="box-check"></span><br>Whole family: every spot <span class="box-check"></span><br>Oven: two zones <span class="box-check"></span><br>Detour to: <span class="blank" style="display:inline-block;width:1.1in"></span></p>
    </div>
  </div>
  <p class="sheet-note">Too Late beats everything: the moment the coin reaches it, the flock wins, even in the middle of a turn.</p>
</section>
`;
}

function tokensSheet() {
  const tk = (cls, text) => `    <div class="tk ${cls}">${text}</div>`;
  const turkeys = GG.turkeys.map(t => tk("big", t.name));
  const huh = Array.from({ length: 20 }, (_, i) => tk("huh", `Huh?<br>${i + 1}`));
  const feathers = Array.from({ length: 4 }, () => tk("", "Feather"));
  return `<!-- Generated by book/tools/sheets.mjs from module/config.mjs: edit those, not this file. -->
<section class="sheet" id="sheet-tokens">
  <h2>Tokens</h2>
  <p class="sheet-intro">Cut these out, or use coins and buttons. Turn a turkey face down when it’s Spotted. Put the “Huh?” tokens down in number order, so the highest number out is the newest. When the next number is already on the map, renumber the tokens there from 1 in the same order. If all 20 are down, use a coin as the newest.</p>
  <p class="tokens-label">The flock</p>
  <div class="tokens">
${turkeys.join("\n")}
  </div>
  <p class="tokens-label">The farm</p>
  <div class="tokens">
${[tk("big sq", "Farmer"), tk("big sq", "Dog"), tk("big sq", "Kid"), tk("big sq", "Decoy"), tk("sq", "Clock"), tk("sq", "Clock (spare)")].join("\n")}
  </div>
  <p class="tokens-label">“Huh?” tokens</p>
  <div class="tokens small">
${huh.join("\n")}
  </div>
  <p class="tokens-label">Feathers</p>
  <div class="tokens">
${feathers.join("\n")}
  </div>
</section>
`;
}

export const SHEETS = {
  "42-sheet-turkeys-1.html": () => turkeySheet(1, GG.turkeys.slice(0, 4)),
  "43-sheet-turkeys-2.html": () => turkeySheet(2, GG.turkeys.slice(4, 8)),
  "44-sheet-clock.html": clockSheet,
  "45-sheet-tokens.html": tokensSheet
};

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const [f, make] of Object.entries(SHEETS)) { writeFileSync(join(CH, f), make()); console.log(`wrote ${f}`); }
}
